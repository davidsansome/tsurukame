import Foundation

/**
 * How common a vocabulary word is. Generated by word_frequency/generate.swift from JMdict, and the
 * jiten.moe and wordfreq frequency lists.
 */
public struct WordFrequency: Equatable {
  /** Whether JMdict marks this word as common. */
  public let isCommon: Bool

  /**
   * The word's approximate position in a frequency list, where 1 is the most frequent. This is the
   * geometric mean of its ranks in several lists.
   */
  public let rank: Int?

  public init(isCommon: Bool, rank: Int?) {
    self.isCommon = isCommon
    self.rank = rank
  }

  /** Returns the frequency of the vocabulary subject with this ID, or nil if it's not known. */
  public static func forSubject(id: Int64) -> WordFrequency? {
    kWordFrequencies[id]
  }

  // Upper bounds of the bands that ranks are grouped into.
  private static let kBands = [1000, 2000, 3000, 4000, 5000, 6000, 8000, 10000, 15000, 20000,
                               30000, 50000]

  /** A rough range that the rank falls in, like "8k – 10k". */
  public var rankBand: String? {
    guard let rank = rank else {
      return nil
    }
    guard let upperIndex = WordFrequency.kBands.firstIndex(where: { rank <= $0 }) else {
      return "\(WordFrequency.thousands(WordFrequency.kBands.last!))+"
    }
    let upper = WordFrequency.kBands[upperIndex]
    if upperIndex == 0 {
      return "Top \(WordFrequency.thousands(upper))"
    }
    let lower = WordFrequency.kBands[upperIndex - 1]
    return "\(WordFrequency.thousands(lower)) – \(WordFrequency.thousands(upper))"
  }

  private static func thousands(_ n: Int) -> String {
    "\(n / 1000)k"
  }
}

private let kWordFrequencies: [Int64: WordFrequency] = {
  let path = Bundle.module.path(forResource: "word-frequency.json", ofType: nil)!
  let data = try! Data(contentsOf: URL(fileURLWithPath: path))
  // Each entry is "subject ID": [rank, common], where a rank of 0 means it's not known, and
  // common is 1 or 0.
  let json = try! JSONSerialization.jsonObject(with: data) as! [String: [Int]]

  var ret = [Int64: WordFrequency]()
  for (id, fields) in json {
    ret[Int64(id)!] = WordFrequency(isCommon: fields[1] != 0,
                                    rank: fields[0] == 0 ? nil : fields[0])
  }
  return ret
}()
